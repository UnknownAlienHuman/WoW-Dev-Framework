    #[test]
    fn complete_draft_supports_authoritative_exact_lookup() -> Result<(), Box<dyn Error>> {
        let index = BlizzardApiIndex::from_json(&fixture(true)?)?;
        match index.function("C_Example.Lookup") {
            BlizzardApiLookup::Found(record) => assert_eq!(record.name, "Lookup"),
            other => return Err(format!("unexpected lookup outcome: {other:?}").into()),
        }
        assert_eq!(
            index.function("C_Example.Missing"),
            BlizzardApiLookup::AuthoritativeAbsence
        );
        assert_eq!(index.events_by_literal("EXAMPLE_CHANGED").len(), 1);
        Ok(())
    }

    #[test]
    fn partial_draft_cannot_prove_absence() -> Result<(), Box<dyn Error>> {
        let index = BlizzardApiIndex::from_json(&fixture(false)?)?;
        assert_eq!(
            index.table("C_Example.Missing"),
            BlizzardApiLookup::NotAuthoritativeAbsence
        );
        Ok(())
    }

