//! Verified ingestion and exact lookup for normalized Blizzard generated-API drafts.
//!
//! The source revision is evidence attached to one completed draft. It is not a
//! permanent upstream pin: callers resolve a moving source selector again for
//! every new operation and then pass the resulting exact draft here.

use std::collections::{BTreeMap, BTreeSet};
use std::error::Error;
use std::fmt;

use serde::{Deserialize, Serialize};
use serde_json::Value;
use sha2::{Digest, Sha256};
use wow_core::canonical_json_bytes;

/// Current normalized draft schema understood by this adapter.
pub const BLIZZARD_API_DRAFT_SCHEMA: &str = "wow.reference-draft.blizzard-generated-api/v1";

/// Failure while decoding or verifying a generated-API draft.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum BlizzardApiDraftError {
    /// The JSON representation could not be decoded.
    Json(String),
    /// Canonical JSON could not be produced.
    Canonical(String),
    /// One schema invariant was violated.
    Invalid(String),
}

impl fmt::Display for BlizzardApiDraftError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Json(message) => write!(formatter, "invalid Blizzard API draft JSON: {message}"),
            Self::Canonical(message) => {
                write!(formatter, "cannot canonicalize Blizzard API draft: {message}")
            }
            Self::Invalid(message) => write!(formatter, "invalid Blizzard API draft: {message}"),
        }
    }
}

impl Error for BlizzardApiDraftError {}

fn invalid(message: impl Into<String>) -> BlizzardApiDraftError {
    BlizzardApiDraftError::Invalid(message.into())
}

fn is_sha256(value: &str) -> bool {
    value.len() == 71
        && value.starts_with("sha256:")
        && value[7..]
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
}

fn is_git_object_id(value: &str) -> bool {
    (40..=64).contains(&value.len())
        && value
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
}

fn bytes_to_hex(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut result = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        result.push(char::from(HEX[usize::from(byte >> 4)]));
        result.push(char::from(HEX[usize::from(byte & 0x0f)]));
    }
    result
}

fn raw_draft_digest(root: &Value) -> Result<String, BlizzardApiDraftError> {
    let mut projection = root.clone();
    let object = projection
        .as_object_mut()
        .ok_or_else(|| invalid("root must be a JSON object"))?;
    object.remove("draft_digest");
    let canonical = canonical_json_bytes(&projection)
        .map_err(|error| BlizzardApiDraftError::Canonical(error.to_string()))?;
    let digest = Sha256::digest(canonical);
    Ok(format!("sha256:{}", bytes_to_hex(&digest)))
}

