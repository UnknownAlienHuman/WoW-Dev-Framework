//! Separate immutable source universes for generated-to-source navigation.
use super::{LookupError, MAX_FILES, check_cancelled};
use crate::native::{AnnotationFile, NativeLibrary, SourceLink};
use std::collections::BTreeMap;
use std::sync::atomic::AtomicBool;
use wow_reference::native::source_digest;

/// A viewed source file, independent of any particular descriptor range.
/// `None` identifies Blizzard input; external aliases use their explicit scope.
#[derive(Clone, Copy, Debug)]
pub struct SourceFile<'a> {
    pub scope: Option<&'a str>,
    pub revision: &'a str,
    pub path: &'a str,
    pub sha256: &'a str,
}

struct Identity<'a> {
    revision: &'a str,
    sha256: &'a str,
    bytes: usize,
}

#[derive(Debug)]
struct RetainedIdentity {
    revision: Box<str>,
    sha256: Box<str>,
    bytes: usize,
}

#[derive(Debug)]
struct RetainedFile {
    sha256: Box<str>,
    bytes: usize,
    mappings: String,
    mapping_bytes: usize,
}

/// Sealed, nonserialized custody of the original native navigation inputs.
/// Source bytes are not copied. Generated file and complete mapping inventories
/// remain exact; replacing or filtering mappings cannot acquire this custody.
#[derive(Debug)]
pub struct NavigationSourceInventory {
    blizzard: BTreeMap<Box<str>, RetainedIdentity>,
    aliases: BTreeMap<Box<str>, RetainedIdentity>,
    files: BTreeMap<Box<str>, RetainedFile>,
    metadata_bytes: usize,
}

impl NavigationSourceInventory {
    pub fn from_library(
        library: &NativeLibrary<'_>,
        cancelled: &AtomicBool,
    ) -> Result<Self, LookupError> {
        super::validate_library(library, cancelled)?;
        let sources = Sources::new(library, cancelled)?;
        let mut result = Self {
            blizzard: BTreeMap::new(),
            aliases: BTreeMap::new(),
            files: BTreeMap::new(),
            metadata_bytes: 0,
        };
        for (original, retained) in [
            (&sources.blizzard, &mut result.blizzard),
            (&sources.aliases, &mut result.aliases),
        ] {
            for (&path, identity) in original {
                check_cancelled(cancelled)?;
                result.metadata_bytes = super::retained::charge(
                    result.metadata_bytes,
                    [
                        path.len(),
                        identity.revision.len(),
                        identity.sha256.len(),
                        256,
                    ],
                )?;
                retained.insert(
                    path.into(),
                    RetainedIdentity {
                        revision: identity.revision.into(),
                        sha256: identity.sha256.into(),
                        bytes: identity.bytes,
                    },
                );
            }
        }
        let mut generated_bytes = 0usize;
        let mut mappings = 0usize;
        let mut mapping_bytes = 0usize;
        for file in &library.files {
            check_cancelled(cancelled)?;
            super::validate_file(file, &file.sha256, cancelled)?;
            generated_bytes = generated_bytes
                .checked_add(file.text.len())
                .ok_or(LookupError::InputLimit)?;
            mappings = mappings
                .checked_add(file.mappings.len())
                .ok_or(LookupError::InputLimit)?;
            if generated_bytes > 64 * 1024 * 1024 || mappings > 262_144 {
                return Err(LookupError::InputLimit);
            }
            for mapping in &file.mappings {
                check_cancelled(cancelled)?;
                super::rank(mapping.granularity)?;
                let span = mapping.generated;
                if span.start >= span.end || file.text.get(span.start..span.end).is_none() {
                    return Err(LookupError::InvalidMapping);
                }
                sources.revision(&mapping.source)?;
            }
            result.metadata_bytes = super::retained::charge(
                result.metadata_bytes,
                [file.path.len(), file.sha256.len(), 256],
            )?;
            let (mapping_digest, serialized_bytes) = super::retained::mapping_digest(
                file,
                super::retained::MAX_MAPPING_BYTES - mapping_bytes,
                cancelled,
            )?;
            mapping_bytes += serialized_bytes;
            let identity = RetainedFile {
                sha256: file.sha256.clone().into_boxed_str(),
                bytes: file.text.len(),
                mappings: mapping_digest,
                mapping_bytes: serialized_bytes,
            };
            if result
                .files
                .insert(file.path.clone().into_boxed_str(), identity)
                .is_some()
            {
                return Err(LookupError::InvalidMapping);
            }
        }
        check_cancelled(cancelled)?;
        Ok(result)
    }

    /// Charged retained descriptors, excluding borrowed source/generated bytes.
    #[must_use]
    pub const fn metadata_bytes(&self) -> usize {
        self.metadata_bytes
    }

    pub(super) fn validate_files(
        &self,
        files: &[AnnotationFile],
        cancelled: &AtomicBool,
    ) -> Result<(), LookupError> {
        check_cancelled(cancelled)?;
        if files.len() != self.files.len() {
            return Err(LookupError::StaleArtifact);
        }
        let mut seen = std::collections::BTreeSet::new();
        for file in files {
            check_cancelled(cancelled)?;
            let identity = self
                .files
                .get(file.path.as_str())
                .ok_or(LookupError::StaleArtifact)?;
            if !seen.insert(file.path.as_str())
                || file.sha256.as_str() != identity.sha256.as_ref()
                || file.text.len() != identity.bytes
                || {
                    let (digest, bytes) =
                        super::retained::mapping_digest(file, identity.mapping_bytes, cancelled)?;
                    digest != identity.mappings || bytes != identity.mapping_bytes
                }
            {
                return Err(LookupError::StaleArtifact);
            }
        }
        check_cancelled(cancelled)
    }
}

pub(super) struct Sources<'a> {
    blizzard: BTreeMap<&'a str, Identity<'a>>,
    aliases: BTreeMap<&'a str, Identity<'a>>,
}

impl<'a> Sources<'a> {
    pub(super) fn from_retained(
        inventory: &'a NavigationSourceInventory,
        cancelled: &AtomicBool,
    ) -> Result<Self, LookupError> {
        let mut result = Self {
            blizzard: BTreeMap::new(),
            aliases: BTreeMap::new(),
        };
        for (original, borrowed) in [
            (&inventory.blizzard, &mut result.blizzard),
            (&inventory.aliases, &mut result.aliases),
        ] {
            for (path, identity) in original {
                check_cancelled(cancelled)?;
                borrowed.insert(
                    path.as_ref(),
                    Identity {
                        revision: &identity.revision,
                        sha256: &identity.sha256,
                        bytes: identity.bytes,
                    },
                );
            }
        }
        check_cancelled(cancelled)?;
        Ok(result)
    }
    pub(super) fn new(
        library: &'a NativeLibrary<'_>,
        cancelled: &AtomicBool,
    ) -> Result<Self, LookupError> {
        if library.sources.is_empty() {
            return Err(LookupError::InvalidMapping);
        }
        if library.sources.len() > MAX_FILES {
            return Err(LookupError::InputLimit);
        }
        let mut result = Self {
            blizzard: BTreeMap::new(),
            aliases: BTreeMap::new(),
        };
        for document in &library.sources {
            check_cancelled(cancelled)?;
            if document.revision() != library.revision {
                return Err(LookupError::InvalidMapping);
            }
            let identity = Identity {
                revision: document.revision(),
                sha256: document.sha256(),
                bytes: document.source_bytes(),
            };
            if result.blizzard.insert(document.path(), identity).is_some() {
                return Err(LookupError::InvalidMapping);
            }
        }
        if let Some(report) = &library.aliases {
            if !matches!(library.schema, "wow-native-annotation-library/5")
                || !matches!(
                    report.schema,
                    "wow-native-alias-projection/1"
                        | "wow-native-alias-projection/2"
                        | "wow-native-alias-projection/3"
                        | "wow-native-alias-projection/4"
                        | "wow-native-alias-projection/5"
                        | "wow-native-alias-projection/6"
                        | "wow-native-alias-projection/7"
                        | "wow-native-alias-projection/8"
                        | "wow-native-alias-projection/9"
                )
            {
                return Err(LookupError::UnsupportedProfile);
            }
            if report.authority != "external_annotation_overlay"
                || report.additional_sources.len() >= crate::aliases::MAX_CATALOG_FILES
            {
                return Err(LookupError::InvalidMapping);
            }
            for document in
                std::iter::once(report.source).chain(report.additional_sources.iter().copied())
            {
                check_cancelled(cancelled)?;
                if document.revision() != report.source.revision() {
                    return Err(LookupError::InvalidMapping);
                }
                let identity = Identity {
                    revision: document.revision(),
                    sha256: document.sha256(),
                    bytes: document.text().len(),
                };
                if result.aliases.insert(document.path(), identity).is_some() {
                    return Err(LookupError::InvalidMapping);
                }
            }
        }
        Ok(result)
    }

    pub(super) fn validate_text(
        &self,
        file: SourceFile<'_>,
        text: &str,
        cancelled: &AtomicBool,
    ) -> Result<(), LookupError> {
        check_cancelled(cancelled)?;
        let identity = self.identity(file.scope, file.path)?;
        // Check byte bounds and the recorded length before hashing caller input.
        if text.len() > crate::ketho::MAX_OUTPUT_BYTES {
            return Err(LookupError::InputLimit);
        }
        if file.revision != identity.revision
            || file.sha256 != identity.sha256
            || text.len() != identity.bytes
            || source_digest(text.as_bytes()) != identity.sha256
        {
            return Err(LookupError::StaleArtifact);
        }
        check_cancelled(cancelled)
    }

    fn identity(&self, scope: Option<&str>, path: &str) -> Result<&Identity<'a>, LookupError> {
        let sources = match scope {
            None => &self.blizzard,
            Some("annotation_alias_catalog") => &self.aliases,
            _ => return Err(LookupError::UnsupportedProfile),
        };
        sources.get(path).ok_or(LookupError::InvalidMapping)
    }

    pub(super) fn revision(&self, link: &SourceLink) -> Result<&'a str, LookupError> {
        let identity = self.identity(link.scope, &link.path)?;
        if link.sha256 != identity.sha256
            || link.span.start >= link.span.end
            || link.span.end > identity.bytes
        {
            return Err(LookupError::InvalidMapping);
        }
        Ok(identity.revision)
    }
}
